use crate::chat::{
    ChatError, Msg,
    common::{ContentPart, ToolCallRequest},
};
use async_trait::async_trait;

#[async_trait]
pub trait ChatModel: Send + Sync {
    /// Returns this chat model's name.
    fn model_name(&self) -> &str;

    /// Generates a chat response, potentially including text and/or tool call requests.
    async fn generate(
        &self,
        messages: &[Msg],
        options: &ChatOptions,
    ) -> Result<ChatResponse, ChatError>;
}

#[derive(Debug, Clone, Default)]
pub struct ChatOptions {
    pub temperature: Option<f32>,
    pub max_tokens: Option<u32>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ChatResponse {
    /// The content generated by the assistant.
    pub content: Vec<ContentPart>,

    /// List of tool calls requested by the model in this turn.
    pub tool_calls: Vec<ToolCallRequest>,

    pub usage: Option<UsageInfo>,
    pub finish_reason: Option<FinishReason>,
    pub model_id: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct UsageInfo {
    pub prompt_tokens: Option<u32>,
    pub completion_tokens: Option<u32>,
    pub total_tokens: Option<u32>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FinishReason {
    Stop,
    Length,
    ContentFilter,
    ToolCalls,
    Unspecified,
    Other(String),
}
